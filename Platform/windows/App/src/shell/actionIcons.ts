// **动作图标集**（T-20261013-053：全部图标化 + 图标须有明显含义）—— 本侧唯一出处
//
// ## 为什么单独一份（不并进 `nodeIcon.ts`）
//
// `nodeIcon.ts` 管的是**对象树节点类型**（库 / 表 / 列…）—— 那是"这东西是什么"；
// 本文件管的是**动作**（打开 / 删除 / 复制…）—— 那是"按下去会做什么"。
// 两者语义不同、消费面不同（一个是树，一个是按钮），混在一起会让"同动作同图标"这条判据难落。
//
// ## 三条硬纪律（对应 T-053 的加令）
//
// 1. **可识别性**：每个图标名必须**一眼看出动作**，不许用抽象符号 / 通用形状糊弄
//    （明文禁：一律 `⋯` / `□` / `○`）。所以下面每个名字后面都写"语义依据"。
// 2. **同族一致性**：**同一个动作全仓只用一个图标名**（映射表 = `actionIcon.ts`，
//    判据按它机械断言；同一动作出现两个名字 ⇒ 判红）。
// 3. **零依赖**：内联 SVG 路径，不引图标字体 / CDN（断网不能缺图标；本侧要求零第三方依赖）。

/** 动作图标名（**语义名**，不是字体名 / SF Symbol 名）。 */
export type ActionGlyph =
  // ── 文件与工作区 ──────────────────────────────────────────────
  | 'openFolder'    // 打开工作区/目录：文件夹张口 —— 与"新建文件夹"（加号）区分
  | 'closeFolder'   // 关闭工作区：文件夹 + 减号
  | 'newFile'       // 新建文件：纸 + 加号
  | 'newFolder'     // 新建文件夹：文件夹 + 加号
  | 'save'          // 保存：软盘（跨端最普认）
  | 'diff'          // 比对：两支箭头对向（差异）
  | 'trash'         // 删除/移入回收站：垃圾桶
  // ── 检索与替换 ────────────────────────────────────────────────
  | 'search'        // 搜索：放大镜
  | 'replace'       // 替换：两个箭头 + 交换（区别于 search）
  | 'preview'       // 预览：眼睛
  | 'chatBubble'    // 与模型对话：对话气泡（"说话"的通用记号，不是侧栏、也不是"生成"）
  // ── 通用动作 ──────────────────────────────────────────────────
  | 'plus'          // 新建/新增：加号
  | 'close'         // 关闭/取消：叉
  | 'check'         // 确认/提交：勾
  | 'pencil'        // 编辑/重命名：铅笔
  | 'copy'          // 复制：双页
  | 'play'          // 执行/运行：实心三角
  | 'stop'          // 停止：实心方
  | 'eraser'        // 清空（不清数据）：橡皮
  | 'download'      // 导出到文件：向下箭头入盘
  | 'upload'        // 导入：向上箭头出盘
  | 'flask'         // 试跑（跑完回滚）：试管
  | 'wand'          // 生成（SQL/语句）：魔法棒
  | 'code'          // 代码/语句
  | 'sliders'       // 管理面板：滑杆（设置族）
  | 'lock'          // 只读：锁
  | 'sortAsc'       // 升序：箭头向上 + 横线
  | 'sortDesc'      // 降序：箭头向下 + 横线
  | 'chevronLeft'   // 上一页：左尖角
  | 'chevronRight'  // 下一页：右尖角
  | 'chevronDown'   // 展开：下尖角
  | 'chevronUp'     // 收起：上尖角
  | 'arrowRight'    // 跳转：右箭头
  | 'undo'          // 重新打开 / 撤销：回转箭头
  | 'refresh'       // 刷新：环形箭头
  | 'placeholder'   // 未开工占位：空方框

